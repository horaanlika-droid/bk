def slug(s):
    return re.sub(r"[^\w]+", "-", s.lower()).strip("-")

path = pathlib.Path(__file__).resolve().parent.parent / "menu.json"
menu = json.loads(path.read_text("utf-8"))
have = {p["id"] for p in menu}
for group, rows in items.items():
    for name, desc, weight, price in rows:
        pid = slug(name)
        if pid in have:
            continue
        menu.append({"id": pid, "name": name, "category": "Еда", "price": price,
                     "desc": desc, "weight": weight, "group": group})
path.write_text(json.dumps(menu, ensure_ascii=False, indent=2) + "\n", "utf-8")
print(len(menu))
